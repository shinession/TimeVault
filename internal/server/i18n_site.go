// The texts of the Site settings page (web/templates/site.html): the page itself, one title and hint for each group
// of settings (site.g.<group>, site.gh.<group>), and a label and an explanation for each setting (site.f.<key>,
// site.h.<key>). The keys of the settings are the ones of config.SiteSettings; a test checks that every setting has
// its texts in both languages.
func init() {
	for lang, texts := range map[string]map[string]string{"en": siteEN, "zh": siteZH} {
		for key, text := range texts {
			messages[lang][key] = text
		}
	}
}

